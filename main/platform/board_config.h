#pragma once

#include <stdint.h>

#include "driver/ledc.h"
#include "esp_err.h"

#define PIN_AXIS_FRONT_LEFT_RPWM 4
#define PIN_AXIS_FRONT_LEFT_LPWM 5
#define PIN_AXIS_FRONT_LEFT_ENABLE 6

#define PIN_AXIS_FRONT_RIGHT_RPWM 7
#define PIN_AXIS_FRONT_RIGHT_LPWM 8
#define PIN_AXIS_FRONT_RIGHT_ENABLE 9

#define PIN_AXIS_WING_RPWM 10
#define PIN_AXIS_WING_LPWM 11
#define PIN_AXIS_WING_ENABLE 12

#define PIN_AXIS_FRONT_LEFT_LIMIT_UP 13
#define PIN_AXIS_FRONT_LEFT_LIMIT_DOWN 14
#define PIN_AXIS_FRONT_RIGHT_LIMIT_UP 15
#define PIN_AXIS_FRONT_RIGHT_LIMIT_DOWN 16
#define PIN_AXIS_WING_LIMIT_UP 17
#define PIN_AXIS_WING_LIMIT_DOWN 18

#define PIN_AXIS_FRONT_LEFT_HALL_A 19
#define PIN_AXIS_FRONT_LEFT_HALL_B 20
#define PIN_AXIS_FRONT_RIGHT_HALL_A 38
#define PIN_AXIS_FRONT_RIGHT_HALL_B 39
#define PIN_AXIS_WING_HALL_A 40
#define PIN_AXIS_WING_HALL_B 41

#define PIN_BUTTON_UP 1
#define PIN_BUTTON_DOWN 2
#define PIN_BUTTON_CALIBRATE 21
#define PIN_EMERGENCY_STOP 47
#define PIN_STATUS_LED 48

#define AXIS_FRONT_LEFT_HALL_SIGN 1
#define AXIS_FRONT_RIGHT_HALL_SIGN 1
#define AXIS_WING_HALL_SIGN 1

/* Provisional until measured with the selected actuator under bench testing. */
#define BOARD_ACTUATOR_TRAVEL_UM 500000U
#define AXIS_FRONT_LEFT_COUNTS_PER_TRAVEL 10000U
#define AXIS_FRONT_RIGHT_COUNTS_PER_TRAVEL 10000U
#define AXIS_WING_COUNTS_PER_TRAVEL 10000U
#define BOARD_HALL_FEEDBACK_REQUIRED 1
#define BOARD_HALL_WARNING_UM 3000
#define BOARD_HALL_STOP_UM 5000
#define BOARD_HALL_STALL_TIMEOUT_MS 1000U

#define BOARD_MOTOR_START_DUTY_PERMILLE 300U
#define BOARD_MOTOR_MAX_DUTY_PERMILLE 1000U
#define BOARD_SYNCHRONIZATION_TRIM_PERMILLE 200U

#define MOTOR_PWM_FREQUENCY_HZ 20000U
#define MOTOR_PWM_RESOLUTION LEDC_TIMER_10_BIT
#define MOTOR_PWM_MAX_DUTY 1023U

#define BOARD_CONTROL_TASK_CORE 1
#define BOARD_CONTROL_TASK_PRIORITY 10U
#define BOARD_CONTROL_TASK_STACK_WORDS 3072U
#define BOARD_LOG_TASK_CORE 0
#define BOARD_LOG_TASK_PRIORITY 2U
#define BOARD_LOG_TASK_STACK_WORDS 2048U
#define BOARD_LOG_QUEUE_DEPTH 12U
#define BOARD_CONTROL_REQUEST_QUEUE_DEPTH 8U

_Static_assert(BOARD_ACTUATOR_TRAVEL_UM <= INT32_MAX,
               "actuator travel must fit the domain position type");
_Static_assert(AXIS_FRONT_LEFT_COUNTS_PER_TRAVEL > 0U && AXIS_FRONT_RIGHT_COUNTS_PER_TRAVEL > 0U &&
                   AXIS_WING_COUNTS_PER_TRAVEL > 0U,
               "every Hall scale must be nonzero");
_Static_assert(BOARD_HALL_WARNING_UM > 0 && BOARD_HALL_WARNING_UM < BOARD_HALL_STOP_UM,
               "Hall warning must precede the hard skew stop");
_Static_assert(BOARD_MOTOR_START_DUTY_PERMILLE > 0U &&
                   BOARD_MOTOR_START_DUTY_PERMILLE <= BOARD_MOTOR_MAX_DUTY_PERMILLE &&
                   BOARD_MOTOR_MAX_DUTY_PERMILLE <= 1000U,
               "motor duty configuration is invalid");
_Static_assert(BOARD_SYNCHRONIZATION_TRIM_PERMILLE < BOARD_MOTOR_MAX_DUTY_PERMILLE,
               "synchronization trim must leave positive motor duty");
_Static_assert(BOARD_LOG_QUEUE_DEPTH > 0U && BOARD_CONTROL_REQUEST_QUEUE_DEPTH > 0U,
               "runtime queues must have bounded nonzero capacity");

esp_err_t board_config_validate_pins(void);
